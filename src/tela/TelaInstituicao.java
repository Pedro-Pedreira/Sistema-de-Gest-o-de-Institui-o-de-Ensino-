        private void carregarDadosIniciais() {
        // 1. Curso (Código 1)
        gerenciador.cadastrarCurso(1, "Engenharia de Software", 120.0);

        // 2. Disciplina (Código 10, vinculada ao Curso 1)
        gerenciador.cadastrarDisciplina(10, "Programação Orientada a Objetos", 4, 1);

        // 3. Professor (Código 100)
        gerenciador.cadastrarProfessor(100, "Dr. Alan Turing", "Doutor", "turing@instituicao.edu.br");

        // 4. Alunos (Um Regular código 1000 e um Bolsista código 1001, vinculados ao Curso 1)
        gerenciador.cadastrarAlunoRegular(1000, "João Silva", "joao@email.com", 1);
        gerenciador.cadastrarAlunoBolsista(1001, "Maria Souza", "maria@email.com", 1, "Mérito Acadêmico", 50.0);

        // 5. Turma (Código 500, vinculada à Disciplina 10 e Professor 100, com 30 vagas)
        gerenciador.cadastrarTurma(500, "2026/2", 10, 100, 30);

        // 6. Matrícula inicial (Opcional: já deixa o João matriculado na Turma 500)
        Aluno alunoInicial = gerenciador.buscarAluno(1000);
        Turma turmaInicial = gerenciador.buscarTurma(500);
        gerenciador.matricular(alunoInicial, turmaInicial, "17/11/2026");
    }

