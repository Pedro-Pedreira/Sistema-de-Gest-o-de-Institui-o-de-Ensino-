    private void btnCadastrarAlunoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCadastrarAlunoActionPerformed
        try {
        int codigo = Integer.parseInt(tfCodigoAluno.getText());
        String nome = tfNomeAluno.getText();
        String email = tfEmailAluno.getText();
        int codigoCurso = Integer.parseInt(tfCodigoCursoAluno.getText());

        String resposta;

        // Se a checkbox estiver marcada, cadastra como Bolsista
        if (cbBolsista.isSelected()) {
            String tipoBolsa = tfTipoBolsaAluno.getText();
            double percentualBolsa = Double.parseDouble(tfPercentualBolsaAluno.getText());

            resposta = gerenciador.cadastrarAlunoBolsista(codigo, nome, email, codigoCurso, tipoBolsa, percentualBolsa);
        } else {
            // Caso contrário, cadastra como Aluno Regular
            resposta = gerenciador.cadastrarAlunoRegular(codigo, nome, email, codigoCurso);
        }

        taSaidaAlunos.setText(resposta);

    } catch (NumberFormatException e) {
        taSaidaAlunos.setText("Erro: Verifique se os campos numéricos (Código, Curso e Percentual) foram preenchidos corretamente.");
    }
    }//GEN-LAST:event_btnCadastrarAlunoActionPerformed

